"""Phase 1-2 regression: notes (autosave, no shortcuts while typing, Esc), Notes tab, review mode, quiz answer line, tutor status."""
import json, time, tempfile
from common import *
TAG = 'e2e'
errs = []
with sync_playwright() as p:
  b=p.chromium.launch()
  for W,H in [(1440,900),(1728,1117)]:
    pg=b.new_page(viewport={'width':W,'height':H})
    pg.on('console', lambda m: m.type=='error' and errs.append(m.text))
    pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto(BASE+'/#/'); pg.evaluate("localStorage.clear()"); pg.goto(BASE+'/#/book/heat-mass-transfer'); pg.wait_for_timeout(800)
    ok(pg.locator('.tabs button[disabled]').count()==1, f'{W} review disabled when unmarked')
    pg.goto(BASE+'/#/review/heat-mass-transfer'); pg.wait_for_timeout(500)
    ok('Nothing to review' in pg.inner_text('main'), 'review empty state')
    pg.screenshot(path=f'{OUT}/{TAG}-{W}-review-empty.png')
    pg.goto(BASE+'/#/read/heat-mass-transfer/1/2'); pg.wait_for_timeout(1200)
    cur=lambda: pg.evaluate("JSON.parse(localStorage['learnscroll-study-v1']).books['heat-mass-transfer'].card")
    c0=cur()
    pg.click('.mark[data-mark="n"][data-id="c1-2"]'); pg.wait_for_timeout(200)
    pg.keyboard.type('Remember bd jk space ok'); pg.keyboard.press('Space'); pg.keyboard.type('end'); pg.wait_for_timeout(1000)
    st=pg.evaluate("JSON.parse(localStorage['learnscroll-study-v1']).books['heat-mass-transfer']")
    ok(st['notes'].get('c1-2',{}).get('text')=='Remember bd jk space ok end', 'note autosaved')
    ok(not st['marks'].get('c1-2',{}).get('b') and not st['marks'].get('c1-2',{}).get('d') and cur()==c0, 'typing fired no shortcuts')
    ok('Saved' in pg.inner_text('.note-ed[data-note="c1-2"] .note-status'), 'Saved hint')
    pg.screenshot(path=f'{OUT}/{TAG}-{W}-note-editor.png')
    pg.keyboard.press('Escape'); pg.wait_for_timeout(300)
    ok(pg.locator('.note-ed[data-note="c1-2"]').is_hidden() and '#/read' in pg.url, 'Esc closes editor only')
    pg.keyboard.press('b'); pg.keyboard.press('d'); pg.wait_for_timeout(200)
    pg.reload(); pg.wait_for_timeout(1200)
    ok(pg.locator('.mark.has-note[data-id="c1-2"]').count()==1, 'note indicator persists after reload')
    pg.click('.mark[data-mark="n"][data-id="c1-2"]'); pg.wait_for_timeout(200)
    ok(pg.input_value('#ne-c1-2').startswith('Remember'), 'note text persists')
    pg.screenshot(path=f'{OUT}/{TAG}-{W}-note-indicator.png')
    pg.keyboard.press('Escape')
    # bookmark a quiz card too
    pg.goto(BASE+'/#/read/heat-mass-transfer/1'); pg.wait_for_timeout(800)
    n=pg.locator('.card:not(.end)').count(); pg.goto(BASE+f'/#/read/heat-mass-transfer/1/{n}'); pg.wait_for_timeout(1000); pg.keyboard.press('b'); pg.wait_for_timeout(200)
    # quiz still works
    pg.locator('.card.quiz').last.locator('.opt').first.click(); pg.wait_for_timeout(200); ok('Correct answer' in pg.locator('.card.quiz').last.locator('.feedback').inner_text(),'quiz answer line')
    pg.goto(BASE+'/#/book/heat-mass-transfer/notes'); pg.wait_for_timeout(500)
    ok(pg.locator('.marked a[href="#/read/heat-mass-transfer/1/2"]').count()==1, 'notes tab links card')
    pg.screenshot(path=f'{OUT}/{TAG}-{W}-notes-tab.png')
    pg.goto(BASE+'/#/'); pg.wait_for_timeout(500); pg.screenshot(path=f'{OUT}/{TAG}-{W}-library.png')
    ok(pg.locator('a[href="#/review/heat-mass-transfer"]').count()>=1, 'library review link')
    pg.goto(BASE+'/#/review/heat-mass-transfer'); pg.wait_for_timeout(400); pg.screenshot(path=f'{OUT}/{TAG}-{W}-review-setup.png')
    pg.click('a[href="#/review/heat-mass-transfer/both"]'); pg.wait_for_timeout(500)
    ok(pg.locator('#rv-body').is_hidden(), 'body hidden at prompt'); pg.screenshot(path=f'{OUT}/{TAG}-{W}-review-prompt.png')
    pg.keyboard.press('Space'); pg.wait_for_timeout(300); ok(pg.locator('#rv-body').is_visible(),'Space reveals')
    pg.screenshot(path=f'{OUT}/{TAG}-{W}-review-revealed.png')
    pg.keyboard.press('1'); pg.wait_for_timeout(300)
    pg.click('#rv-reveal'); pg.wait_for_timeout(300); ok('Correct answer' in pg.inner_text('#rv-card'),'quiz reveal shows answer')
    pg.screenshot(path=f'{OUT}/{TAG}-{W}-review-quiz.png')
    pg.keyboard.press('2'); pg.wait_for_timeout(300)
    ok('1 of 2 got it' in pg.inner_text('#rv-card') and pg.locator('#rv-card .marked a').count()==1, 'summary + again links')
    pg.screenshot(path=f'{OUT}/{TAG}-{W}-review-summary.png')
    rv=pg.evaluate("JSON.parse(localStorage['learnscroll-study-v1']).books['heat-mass-transfer'].review")
    ok(rv.get('c1-2',{}).get('r')=='got' and len(rv)==2 and 'again' in [v['r'] for v in rv.values()], 'results saved '+json.dumps({k:v['r'] for k,v in rv.items()}))
    pg.goto(BASE+'/#/review/heat-mass-transfer/both'); pg.reload(); pg.wait_for_timeout(800); pg.screenshot(path=f'{OUT}/{TAG}-{W}-review-last-result.png'); ok('Last review' in pg.inner_text('#rv-card'),'last result shown')
    # tutor status
    r=pg.evaluate("fetch('/api/tutor').then(r=>r.status)"); ok(r==200,'tutor status '+str(r))
    pg.close()
  b.close()
finish(errs)
